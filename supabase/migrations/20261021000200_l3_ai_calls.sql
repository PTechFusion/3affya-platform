-- L3 (task 1.9): ai_calls, one row per call lib/ai makes (lib/ai/log.ts). Architecture observability: model, tokens, cost,
-- latency, pass or fail. A retry after invalid output is its own row (attempt 2); a call refused before it reached the vendor
-- (bad input, circuit open, token cap) is a row with no tokens, so a failed job is explained here. No row ever holds document
-- content or model output: page references are ids ("d1:p2") and failure details are error classes and schema paths.
--
-- Each row belongs to an ai_jobs run (L1, file 7). Inserting a row adds its tokens and cost to that job's running totals in the
-- same statement (trigger below), so ai_jobs.input_tokens, output_tokens and cost_micros are always the sum of the job's calls,
-- the per-job token cap (aiLimits.jobTokenCap) is checked against those totals, and the pipeline never writes them itself.
-- Deleting a job deletes its calls (on delete cascade); jobs outlive their record sets, so the cost history stays.
--
-- Service role only. lib/ai writes with the service client as a named system caller (lib/db/client.ts: inngest, or script for
-- the spike), and the admin AI jobs page (screen 45) reads through server code after the admin's TOTP check. No API role reads
-- or writes a row: all privileges are revoked from anon and authenticated, and a restrictive policy refuses both, so the table
-- has RLS on and a policy (public.schema_security_report() requires both) and nothing but the service role, which bypasses RLS,
-- can touch it.

create table public.ai_calls (
  -- Generated by lib/ai, so a retried insert of the same row is ignored (on conflict do nothing): the write is idempotent.
  id uuid primary key,
  job_id uuid not null references public.ai_jobs (id) on delete cascade,
  step public.pipeline_step not null,
  -- "<document id>:p<page>" for a page call; null for a summary call.
  page_ref text,
  page_id uuid references public.record_pages (id) on delete set null,
  attempt smallint not null default 1,
  vendor text not null,
  -- The id the vendor reported (AI_MODEL, or the Bedrock model id).
  model text not null,
  -- lib/ai/prompts.ts PROMPT_VERSION: which fixed template produced the call.
  prompt_version text not null,
  input_tokens integer not null default 0,
  output_tokens integer not null default 0,
  -- Millionths of cost_currency, rounded up, as ai_jobs.cost_micros (a page costs fractions of a cent).
  cost_micros bigint not null default 0,
  cost_currency text not null default 'USD',
  latency_ms integer not null default 0,
  outcome text not null,
  failure_reason text,
  failure_detail text,
  stop_reason text,
  request_id text,
  created_at timestamptz not null default now(),
  constraint ai_calls_step check (step in ('extract', 'summarise')),
  constraint ai_calls_page_ref check (page_ref ~ '^[A-Za-z0-9_-]{1,64}:p[1-9][0-9]{0,4}$'),
  constraint ai_calls_attempt check (attempt between 1 and 10),
  constraint ai_calls_vendor check (vendor in ('anthropic', 'bedrock')),
  constraint ai_calls_model check (char_length(model) between 1 and 200),
  constraint ai_calls_prompt_version check (char_length(prompt_version) between 1 and 40),
  constraint ai_calls_tokens check (input_tokens >= 0 and output_tokens >= 0),
  constraint ai_calls_cost check (cost_micros >= 0),
  constraint ai_calls_cost_currency check (cost_currency ~ '^[A-Z]{3}$'),
  constraint ai_calls_latency check (latency_ms >= 0),
  constraint ai_calls_outcome check (outcome in ('ok', 'failed')),
  -- lib/ai/log.ts AI_CALL_FAILURES.
  constraint ai_calls_failure_reason check (failure_reason in (
    'bad_input', 'circuit_open', 'token_cap', 'budget_unavailable', 'timeout', 'unavailable', 'rejected', 'refusal',
    'max_tokens', 'invalid_output'
  )),
  constraint ai_calls_failed_have_reason check ((outcome = 'failed') = (failure_reason is not null)),
  constraint ai_calls_failure_detail check (char_length(failure_detail) <= 500),
  constraint ai_calls_stop_reason check (char_length(stop_reason) <= 40),
  constraint ai_calls_request_id check (char_length(request_id) <= 200)
);

create index ai_calls_job_idx on public.ai_calls (job_id, created_at);
-- The daily spend alert and the admin page's spend per day (lib/ai-jobs.ts) read calls by time.
create index ai_calls_created_idx on public.ai_calls (created_at);
create index ai_calls_page_idx on public.ai_calls (page_id) where page_id is not null;

/* ---------------- job totals ---------------- */

create function private.ai_calls_add_to_job() returns trigger
language plpgsql
set search_path = ''
as $$
declare
  job_currency text;
begin
  update public.ai_jobs
     set input_tokens = input_tokens + new.input_tokens,
         output_tokens = output_tokens + new.output_tokens,
         cost_micros = cost_micros + new.cost_micros
   where id = new.job_id
  returning cost_currency into job_currency;
  if job_currency is distinct from new.cost_currency then
    raise exception 'an AI call is costed in % but its job in %', new.cost_currency, coalesce(job_currency, 'no currency')
      using errcode = '23514';
  end if;
  return new;
end;
$$;

create trigger ai_calls_add_to_job after insert on public.ai_calls
  for each row execute function private.ai_calls_add_to_job();

/* ---------------- privileges and policies ---------------- */

alter table public.ai_calls enable row level security;

revoke all on table public.ai_calls from anon, authenticated;

-- Service role only (see the header): refuses every row to the two API roles, for every command, even if a grant ever came back.
create policy ai_calls_service_role_only on public.ai_calls as restrictive for all to anon, authenticated
  using (false)
  with check (false);
