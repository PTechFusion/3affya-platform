// Where the a11y spec writes what axe found, and the summary built from it after the run: one row per rule and colour pair,
// with the routes, locales, widths and screens it was seen on. ops/known_defects.md is written from this summary.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const FINDINGS_DIR = join("test-results", "e2e", "a11y-findings");
export const SUMMARY_FILE = join("test-results", "e2e", "a11y-summary.md");

export type NodeFinding = { target: string; html: string; fg?: string; bg?: string; ratio?: number; known?: string };
export type RuleFinding = { id: string; impact: string; help: string; helpUrl: string; nodes: NodeFinding[] };
export type RouteFindings = { project: string; width: number; locale: string; path: string; screen: string; violations: RuleFinding[] };

export function clearFindings() {
  rmSync(FINDINGS_DIR, { recursive: true, force: true });
  mkdirSync(FINDINGS_DIR, { recursive: true });
}

export function writeFindings(name: string, record: RouteFindings) {
  mkdirSync(FINDINGS_DIR, { recursive: true });
  writeFileSync(join(FINDINGS_DIR, `${name}.json`), JSON.stringify(record, null, 2));
}

const IMPACT_ORDER = ["critical", "serious", "moderate", "minor", "unknown"];
const join2 = (xs: Iterable<string | number>) => [...new Set([...xs].map(String))].sort((a, b) => a.localeCompare(b, "en", { numeric: true })).join(", ");

/** Groups every finding by rule (and colour pair for contrast) into a Markdown table. Returns the row count. */
export function writeSummary(): number {
  if (!existsSync(FINDINGS_DIR)) return 0;
  const records = readdirSync(FINDINGS_DIR)
    .filter((f) => f.endsWith(".json"))
    .map((f) => JSON.parse(readFileSync(join(FINDINGS_DIR, f), "utf8")) as RouteFindings);

  type Row = { impact: string; rule: string; colours: string; known: Set<string>; paths: Set<string>; locales: Set<string>; widths: Set<number>; screens: Set<string>; nodes: number; example: string };
  const rows = new Map<string, Row>();
  for (const r of records) {
    for (const v of r.violations) {
      for (const n of v.nodes) {
        const colours = n.fg ? `${n.fg} on ${n.bg} (${n.ratio}:1)` : "";
        const key = `${v.impact}|${v.id}|${n.fg ?? ""}|${n.bg ?? ""}`;
        const row = rows.get(key) ?? { impact: v.impact, rule: v.id, colours, known: new Set(), paths: new Set(), locales: new Set(), widths: new Set(), screens: new Set(), nodes: 0, example: n.html.replace(/\|/g, "\\|").slice(0, 90) };
        if (n.known) row.known.add(n.known);
        row.paths.add(r.path);
        row.locales.add(r.locale);
        row.widths.add(r.width);
        row.screens.add(r.screen);
        row.nodes++;
        rows.set(key, row);
      }
    }
  }
  const sorted = [...rows.values()].sort((a, b) => IMPACT_ORDER.indexOf(a.impact) - IMPACT_ORDER.indexOf(b.impact) || b.nodes - a.nodes);
  const lines = [
    "# a11y summary (generated by the e2e run; compare with ops/known_defects.md)",
    "",
    `${records.length} route scans.`,
    "",
    "| Impact | Rule | Colours | Known | Screens | Locales | Widths | Nodes | Routes | Example |",
    "|---|---|---|---|---|---|---|---|---|---|",
    ...sorted.map((r) => `| ${r.impact} | ${r.rule} | ${r.colours} | ${join2(r.known) || "NEW"} | ${join2(r.screens)} | ${join2(r.locales)} | ${join2(r.widths)} | ${r.nodes} | ${join2(r.paths)} | \`${r.example}\` |`),
    "",
  ];
  writeFileSync(SUMMARY_FILE, lines.join("\n"));
  return sorted.length;
}
